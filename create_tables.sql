CREATE DATABASE IF NOT EXISTS student_result_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE student_result_db;

CREATE TABLE IF NOT EXISTS admin (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  security_question VARCHAR(255) DEFAULT 'What is your favorite color?',
  security_answer VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS students (
  id INT AUTO_INCREMENT PRIMARY KEY,
  usn VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  father_name VARCHAR(150) DEFAULT NULL,
  class VARCHAR(50) DEFAULT NULL,
  password VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS results (
  id INT AUTO_INCREMENT PRIMARY KEY,
  usn VARCHAR(50) NOT NULL,
  subject VARCHAR(150) NOT NULL,
  marks INT NOT NULL,
  max_marks INT DEFAULT 100,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usn) REFERENCES students(usn) ON DELETE CASCADE,
  UNIQUE KEY unique_usn_subject (usn, subject)
);